// 2. DOM लोड होने पर डेटा को टेम्पलेट में इंजेक्ट करने का फंक्शन
document.addEventListener("DOMContentLoaded", () => {
    // URL से 'id' पैरामीटर निकालना
    const urlParams = new URLSearchParams(window.location.search);
    const ideaId = urlParams.get('id');

    // अगर हम टेम्पलेट पेज पर हैं और 'id' मौजूद है
    if (ideaId && document.getElementById("p-title")) {
        const data = businessDatabase[ideaId];

        if (data) {
            // Meta Tags अपडेट करना (SEO के लिए सबसे महत्वपूर्ण)
            document.title = data.title;
            const metaDesc = document.querySelector('meta[name="description"]');
            if (metaDesc) metaDesc.setAttribute("content", data.description);
            
            // Open Graph Meta Tags अपडेट करना
            const ogTitle = document.querySelector('meta[property="og:title"]');
            if (ogTitle) ogTitle.setAttribute("content", data.title);
            const ogDesc = document.querySelector('meta[property="og:description"]');
            if (ogDesc) ogDesc.setAttribute("content", data.description);

            // HTML Elements में डेटा डालना
            document.getElementById("p-h1").innerText = data.h1;
            document.getElementById("p-tag").innerText = data.tag;
            document.getElementById("p-investment").innerText = data.investment;
            document.getElementById("p-profit").innerText = data.profit;
            document.getElementById("p-location").innerText = data.location;
            document.getElementById("p-overview").innerText = data.overview;

            // स्टेप्स (Steps) की लिस्ट बनाना
            const stepsContainer = document.getElementById("p-steps");
            stepsContainer.innerHTML = ""; // पुराना डेटा साफ़ करना
            data.steps.forEach(step => {
                const li = document.createElement("li");
                li.style.marginBottom = "0.75rem";
                li.innerText = step;
                stepsContainer.appendChild(li);
            });

            // कस्टमाइज्ड ब्रेडक्रंब (Breadcrumb) सेट करना
            const breadcrumbCurrent = document.getElementById("breadcrumb-current");
            if (breadcrumbCurrent) breadcrumbCurrent.innerText = data.tag;

        } else {
            // अगर गलत ID आ जाए तो एरर हैंडलिंग
            document.getElementById("p-h1").innerText = "बिज़नेस आइडिया नहीं मिला!";
            document.getElementById("p-overview").innerText = "कृपया होमपेज या कैटेगरी पेज पर जाकर सही लिंक पर क्लिक करें।";
            document.querySelector(".business-stats").style.display = "none";
        }
    }
});
